import { build } from 'esbuild';
import { chmodSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const outfile=fileURLToPath(new URL('../bin/pi-collab',import.meta.url));
const result=await build({
  absWorkingDir:fileURLToPath(new URL('..',import.meta.url)),
  entryPoints:[fileURLToPath(new URL('../src/cli.ts',import.meta.url))],
  outfile,bundle:true,platform:'node',format:'esm',target:'node22.19',
  charset:'utf8',legalComments:'none',write:false,
  banner:{js:'// Generated by npm run build. Edit src/cli.ts and shared source modules.'},
});
const output=result.outputFiles[0];
if(process.argv.includes('--check')){
  if(readFileSync(outfile,'utf8')!==output.text||(statSync(outfile).mode&0o111)===0){
    throw new Error('bin/pi-collab is stale or not executable; run npm run build');
  }
}else{
  writeFileSync(outfile,output.contents);
  chmodSync(outfile,0o755);
}
